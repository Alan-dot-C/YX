const std::vector<Word>& AllWords() {
    static const std::vector<Word> v(std::begin(kWords), std::end(kWords));
    return v;
}

const Word* FindWord(const std::wstring& name) {
    for (const auto& w : AllWords()) {
        if (_wcsicmp(w.name, name.c_str()) == 0) return &w;
    }
    return nullptr;
}
